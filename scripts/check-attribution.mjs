#!/usr/bin/env node
// The one place that defines what counts as AI attribution
// (docs/spec/05-engineering-handbook.md section 4.1). The commit-message Git
// hook, the Claude Code pre-tool hook, `pnpm verify`, and the `static` job all
// call this file, so the patterns cannot drift between layers.
//
// Usage:
//   check-attribution.mjs --message-file <path>   one commit message (Git hook)
//   check-attribution.mjs --stdin                 any text, such as a pull request description
//   check-attribution.mjs --range <a..b>          every commit in a range: message, author, committer
//   check-attribution.mjs --branch                the commits on this branch that main does not have
//
// Exit codes: 0 clean, 1 attribution found, 2 usage or Git error.

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

/** @typedef {{ id: string, description: string, pattern: RegExp }} Rule */
/** @typedef {{ rule: string, line: number }} Finding */

/** @type {readonly Rule[]} */
export const RULES = [
  {
    id: "co-author-trailer",
    description: "a Co-Authored-By trailer naming Claude or Anthropic",
    pattern: /^\s*co-authored-by:.*\b(?:claude|anthropic)\b/i,
  },
  {
    id: "anthropic-address",
    description: "an anthropic.com email address",
    pattern: /[\w.+-]+@(?:[\w-]+\.)*anthropic\.com\b/i,
  },
  {
    id: "generated-with-line",
    description: 'a "Generated with" or "Generated by" line naming Claude',
    pattern: /\bgenerated\s+(?:with|by)\b.*\bclaude\b/i,
  },
  {
    id: "session-trailer",
    description: "a Claude-Session trailer",
    pattern: /^\s*claude-session\s*:/i,
  },
  {
    id: "session-link",
    description: "a claude.ai session link",
    pattern: /\bclaude\.ai\/(?:code\/)?(?:session|chat)/i,
  },
];

/**
 * @param {string} text
 * @returns {Finding[]}
 */
export function findAttribution(text) {
  /** @type {Finding[]} */
  const findings = [];
  const lines = text.split(/\r?\n/);
  lines.forEach((line, index) => {
    for (const rule of RULES) {
      if (rule.pattern.test(line)) {
        findings.push({ rule: rule.id, line: index + 1 });
      }
    }
  });
  return findings;
}

/**
 * @param {{ name: string, email: string }} identity
 * @returns {string[]}
 */
export function findIdentityAttribution({ name, email }) {
  /** @type {string[]} */
  const rules = [];
  if (/\bclaude\b/i.test(name)) rules.push("ai-identity-name");
  if (/@(?:[\w-]+\.)*anthropic\.com$/i.test(email.trim())) rules.push("ai-identity-address");
  return rules;
}

/**
 * Git hands the commit-msg hook the message before it removes comment lines
 * and the diff that `git commit --verbose` appends below the scissors line.
 * Checking those would report attribution patterns that appear in the diff.
 *
 * @param {string} message
 */
export function stripCommitComments(message) {
  const kept = [];
  for (const line of message.split(/\r?\n/)) {
    if (/^# -+ >8 -+$/.test(line)) break;
    if (line.startsWith("#")) continue;
    kept.push(line);
  }
  return kept.join("\n").replace(/\n+$/, "") + "\n";
}

/** @param {string} id */
function describe(id) {
  if (id === "ai-identity-name") return "an author or committer named Claude";
  if (id === "ai-identity-address") return "an author or committer with an anthropic.com address";
  return RULES.find((rule) => rule.id === id)?.description ?? id;
}

/** @param {string[]} args */
function git(args) {
  return execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
}

/**
 * @param {string} range
 * @returns {string[]}
 */
function checkRange(range) {
  const RECORD = "\u001e";
  const FIELD = "\u001f";
  const log = git([
    "log",
    `--format=%H${FIELD}%an${FIELD}%ae${FIELD}%cn${FIELD}%ce${FIELD}%B${RECORD}`,
    range,
  ]);
  /** @type {string[]} */
  const problems = [];
  for (const record of log.split(RECORD)) {
    const trimmed = record.replace(/^\n/, "");
    if (trimmed === "") continue;
    const [
      sha = "",
      authorName = "",
      authorEmail = "",
      committerName = "",
      committerEmail = "",
      body = "",
    ] = trimmed.split(FIELD);
    const short = sha.slice(0, 12);
    for (const finding of findAttribution(body)) {
      problems.push(
        `${short} message line ${finding.line}: ${finding.rule} (${describe(finding.rule)})`,
      );
    }
    for (const rule of findIdentityAttribution({ name: authorName, email: authorEmail })) {
      problems.push(`${short} author: ${rule} (${describe(rule)})`);
    }
    for (const rule of findIdentityAttribution({ name: committerName, email: committerEmail })) {
      problems.push(`${short} committer: ${rule} (${describe(rule)})`);
    }
  }
  return problems;
}

function branchRange() {
  for (const base of ["origin/main", "main"]) {
    try {
      git(["rev-parse", "--verify", "--quiet", base]);
      const mergeBase = git(["merge-base", base, "HEAD"]).trim();
      return `${mergeBase}..HEAD`;
    } catch {
      // This base does not exist in this clone; try the next one.
    }
  }
  throw new Error("neither origin/main nor main exists");
}

/** @param {string} text */
function textProblems(text) {
  return findAttribution(text).map(
    (finding) => `line ${finding.line}: ${finding.rule} (${describe(finding.rule)})`,
  );
}

/**
 * @param {string[]} argv
 * @returns {number}
 */
export function main(argv) {
  const [mode, value] = argv;
  /** @type {string[]} */
  let problems;
  try {
    if (mode === "--message-file" && value) {
      problems = textProblems(stripCommitComments(readFileSync(value, "utf8")));
    } else if (mode === "--stdin") {
      problems = textProblems(readFileSync(0, "utf8"));
    } else if (mode === "--range" && value) {
      problems = checkRange(value);
    } else if (mode === "--branch") {
      problems = checkRange(branchRange());
    } else {
      process.stderr.write(
        "usage: check-attribution.mjs --message-file <path> | --stdin | --range <a..b> | --branch\n",
      );
      return 2;
    }
  } catch (error) {
    process.stderr.write(
      `check-attribution: ${error instanceof Error ? error.message : String(error)}\n`,
    );
    return 2;
  }
  if (problems.length > 0) {
    process.stderr.write(
      "AI attribution found (docs/spec/05-engineering-handbook.md section 4.1):\n" +
        problems.map((problem) => `  ${problem}\n`).join(""),
    );
    return 1;
  }
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exit(main(process.argv.slice(2)));
}
