import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  findAttribution,
  findIdentityAttribution,
  stripCommitComments,
} from "./check-attribution.mjs";

// The fixtures are assembled from parts so that this file does not itself
// contain a credit line that a repository-wide scan would report.
const CLAUDE = "Cla" + "ude";
const ANTHROPIC_ADDRESS = "noreply@" + "anthropic.com";
const fixtures = {
  coAuthor: `Co-Authored-By: ${CLAUDE} Opus <${ANTHROPIC_ADDRESS}>`,
  coAuthorLower: `co-authored-by: ${CLAUDE.toLowerCase()} <someone@example.com>`,
  coAuthorAnthropic: `Co-authored-by: An${"thropic"} Bot <bot@example.com>`,
  generated: `🤖 Generated with [${CLAUDE} Code](https://claude.com/claude-code)`,
  generatedBy: `Generated by ${CLAUDE}`,
  sessionTrailer: `${CLAUDE}-Session: https://example.com/abc`,
  sessionLink: `See https://${CLAUDE.toLowerCase()}.ai/code/session_01ABCdef for the run`,
  address: `Reviewed-by: someone <${ANTHROPIC_ADDRESS}>`,
} as const;

const cli = join(import.meta.dirname, "check-attribution.mjs");

function runCli(args: string[], input?: string, cwd?: string) {
  return spawnSync("node", [cli, ...args], {
    input,
    cwd,
    encoding: "utf8",
  });
}

describe("findAttribution", () => {
  it.each(Object.entries(fixtures))("[NFR-MAINT-08] reports the %s pattern", (_name, line) => {
    const text = `feat(workspace): show output\n\nBody text.\n\n${line}\n`;
    expect(findAttribution(text)).not.toHaveLength(0);
  });

  it("[NFR-MAINT-08] gives the line number of each finding", () => {
    const text = `fix: one\n\n${fixtures.coAuthor}\n`;
    expect(findAttribution(text)).toEqual([
      { rule: "co-author-trailer", line: 3 },
      { rule: "anthropic-address", line: 3 },
    ]);
  });

  it.each([
    "docs(spec): explain how Claude Code settings turn attribution off",
    "chore: the implementer runs in Claude Code with hooks",
    "feat: generated route types with next typegen",
    "Co-Authored-By: Fahad <fahad@example.com>",
    "test: anthropology fixtures are unrelated",
  ])("[NFR-MAINT-08] does not report a mention of the tool: %s", (text) => {
    expect(findAttribution(text)).toEqual([]);
  });
});

describe("findIdentityAttribution", () => {
  it("[NFR-MAINT-08] reports an author named Claude", () => {
    expect(findIdentityAttribution({ name: CLAUDE, email: "x@example.com" })).toEqual([
      "ai-identity-name",
    ]);
  });

  it("[NFR-MAINT-08] reports an address at anthropic.com", () => {
    expect(findIdentityAttribution({ name: "Bot", email: ANTHROPIC_ADDRESS })).toEqual([
      "ai-identity-address",
    ]);
  });

  it("[NFR-MAINT-08] accepts the owner's identity", () => {
    expect(findIdentityAttribution({ name: "Fahad", email: "fahad@example.com" })).toEqual([]);
  });
});

describe("stripCommitComments", () => {
  it("[NFR-MAINT-08] drops comment lines and everything below the scissors line", () => {
    const message = [
      "feat: one",
      "",
      "# Please enter the commit message",
      "# ------------------------ >8 ------------------------",
      `+ ${fixtures.coAuthor}`,
    ].join("\n");
    expect(stripCommitComments(message)).toBe("feat: one\n");
  });
});

describe("command line", () => {
  it("[NFR-MAINT-08] fails a commit message file that carries a co-author trailer", () => {
    const dir = mkdtempSync(join(tmpdir(), "attribution-"));
    const file = join(dir, "COMMIT_EDITMSG");
    writeFileSync(file, `feat: one\n\n${fixtures.coAuthor}\n`);
    const result = runCli(["--message-file", file]);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("co-author-trailer");
  });

  it("[NFR-MAINT-08] passes a clean commit message file", () => {
    const dir = mkdtempSync(join(tmpdir(), "attribution-"));
    const file = join(dir, "COMMIT_EDITMSG");
    writeFileSync(file, "feat: one\n\nPlain body.\n");
    expect(runCli(["--message-file", file]).status).toBe(0);
  });

  it("[NFR-MAINT-08] fails a pull request description read from standard input", () => {
    const result = runCli(["--stdin"], `## What and why\n\n${fixtures.generated}\n`);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("generated-with-line");
  });

  it("[NFR-MAINT-08] checks the messages and identities of every commit in a range", () => {
    const repo = mkdtempSync(join(tmpdir(), "attribution-repo-"));
    const git = (...args: string[]) => execFileSync("git", args, { cwd: repo, encoding: "utf8" });
    git("init", "--quiet", "--initial-branch=main");
    git("config", "user.name", "Fahad");
    git("config", "user.email", "fahad@example.com");
    git("config", "core.hooksPath", "/dev/null");
    git("commit", "--quiet", "--allow-empty", "-m", "chore: base");
    const base = git("rev-parse", "HEAD").trim();
    git("commit", "--quiet", "--allow-empty", "-m", "feat: clean");
    expect(runCli(["--range", `${base}..HEAD`], undefined, repo).status).toBe(0);

    git(
      "-c",
      `user.name=${CLAUDE}`,
      "-c",
      `user.email=${ANTHROPIC_ADDRESS}`,
      "commit",
      "--quiet",
      "--allow-empty",
      "-m",
      "feat: second",
    );
    const result = runCli(["--range", `${base}..HEAD`], undefined, repo);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("ai-identity-name");
    expect(result.stderr).toContain("ai-identity-address");
  });

  it("[NFR-MAINT-08] refuses to run without a mode", () => {
    expect(runCli([]).status).toBe(2);
  });
});
